// ── File System API (IndexedDB handle persistence) ────────────

const _IDB_DB    = 'pokemonAdmin';
const _IDB_STORE = 'fs';
const _IDB_KEY   = 'configHandle';

function _idbOpen() {
  return new Promise((res, rej) => {
    const req = indexedDB.open(_IDB_DB, 1);
    req.onupgradeneeded = e => e.target.result.createObjectStore(_IDB_STORE);
    req.onsuccess = e => res(e.target.result);
    req.onerror   = () => rej(req.error);
  });
}

async function _idbGetHandle() {
  try {
    const db = await _idbOpen();
    return new Promise(res => {
      const tx = db.transaction(_IDB_STORE, 'readonly');
      const r  = tx.objectStore(_IDB_STORE).get(_IDB_KEY);
      r.onsuccess = () => res(r.result || null);
      r.onerror   = () => res(null);
    });
  } catch { return null; }
}

async function _idbSetHandle(handle) {
  try {
    const db = await _idbOpen();
    return new Promise(res => {
      const tx = db.transaction(_IDB_STORE, 'readwrite');
      tx.objectStore(_IDB_STORE).put(handle, _IDB_KEY);
      tx.oncomplete = res;
    });
  } catch {}
}

async function _idbClearHandle() {
  try {
    const db = await _idbOpen();
    return new Promise(res => {
      const tx = db.transaction(_IDB_STORE, 'readwrite');
      tx.objectStore(_IDB_STORE).delete(_IDB_KEY);
      tx.oncomplete = res;
    });
  } catch {}
}

