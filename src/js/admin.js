function renderBossSection(floorNum) {
  const container = document.getElementById('boss-section');
  container.innerHTML = '';

  // Ensure boss entry exists
  if (!config.floors[floorNum].boss) {
    const bd = (typeof BOSSES !== 'undefined' && BOSSES[`floor${floorNum}`]) || null;
    config.floors[floorNum].boss = bd
      ? { pad: bd.pad, level: bd.level, fixedMoves: [...(bd.movepool || [])], randomPool: [], randomCount: 0 }
      : { pad: null, level: 1, fixedMoves: [], randomPool: [], randomCount: 0 };
  }
  const boss = config.floors[floorNum].boss;

  // Header
  const header = document.createElement('div');
  header.className = 'boss-section-header';
  header.innerHTML = '<span class="boss-label">⚔ BOSS</span>';
  container.appendChild(header);

  // Pokemon row
  const bossRow = document.createElement('div');
  bossRow.className = 'boss-poke-row';
  const name = boss.pad ? (typeof padToName === 'function' ? padToName(boss.pad) : boss.pad) : '—';
  bossRow.innerHTML = `
    <canvas class="admin-sprite boss-sprite" width="48" height="48"></canvas>
    <div class="boss-poke-info">
      <span class="boss-poke-name">${name}</span>
      <span class="boss-poke-id">${boss.pad ? '#' + boss.pad : ''}</span>
    </div>
    <label class="boss-level-label">Lv</label>
    <input type="number" class="num-input sm" id="boss-level-inp" value="${boss.level || 1}" min="1" max="100">
    <button class="boss-change-btn">Change</button>
  `;
  if (boss.pad) drawAdminSprite(bossRow.querySelector('.boss-sprite'), boss.pad);
  bossRow.querySelector('#boss-level-inp').addEventListener('change', e => {
    config.floors[floorNum].boss.level = Math.max(1, parseInt(e.target.value) || 1);
  });
  container.appendChild(bossRow);

  // Inline search (hidden by default)
  const searchWrap = document.createElement('div');
  searchWrap.className = 'boss-search-wrap hidden';
  const searchInput = document.createElement('input');
  searchInput.type = 'text';
  searchInput.className = 'boss-search-input';
  searchInput.placeholder = 'Search Pokémon name or #number…';
  searchInput.autocomplete = 'off';
  const searchResults = document.createElement('div');
  searchResults.className = 'boss-search-results hidden';
  searchWrap.appendChild(searchInput);
  searchWrap.appendChild(searchResults);
  container.appendChild(searchWrap);

  bossRow.querySelector('.boss-change-btn').addEventListener('click', () => {
    searchWrap.classList.toggle('hidden');
    if (!searchWrap.classList.contains('hidden')) searchInput.focus();
  });

  let debounce = null;
  searchInput.addEventListener('input', () => {
    clearTimeout(debounce);
    const q = searchInput.value.trim().toLowerCase();
    if (!q) { searchResults.innerHTML = ''; searchResults.classList.add('hidden'); return; }
    debounce = setTimeout(() => {
      const matches = [];
      for (let id = 1; id <= 251; id++) {
        const pad  = String(id).padStart(4, '0');
        const nm   = (typeof padToName === 'function') ? padToName(pad) : `#${pad}`;
        if (nm.toLowerCase().includes(q) || pad.includes(q) || String(id).includes(q)) matches.push({ pad, nm });
        if (matches.length >= 10) break;
      }
      searchResults.innerHTML = '';
      if (!matches.length) {
        searchResults.innerHTML = '<div class="no-results">No Pokémon found</div>';
      } else {
        matches.forEach(m => {
          const item = document.createElement('div');
          item.className = 'search-item';
          item.innerHTML = `<span class="sr-num">#${m.pad}</span><span class="sr-name">${m.nm}</span>`;
          item.addEventListener('mousedown', e => {
            e.preventDefault();
            config.floors[floorNum].boss.pad = m.pad;
            renderBossSection(floorNum);
          });
          searchResults.appendChild(item);
        });
      }
      searchResults.classList.remove('hidden');
    }, 150);
  });

  // 이전 리스너 제거 후 재등록 (floor 탭 전환 시 누적 방지)
  if (container._bossClickHandler) document.removeEventListener('click', container._bossClickHandler);
  container._bossClickHandler = e => {
    if (!searchWrap.contains(e.target) && !bossRow.contains(e.target)) {
      searchResults.classList.add('hidden');
    }
  };
  document.addEventListener('click', container._bossClickHandler);

  // Move config
  const moveCfg = document.createElement('div');
  moveCfg.className = 'boss-moves-cfg';
  container.appendChild(moveCfg);
  renderBossMoveCfg(moveCfg, floorNum);
}

