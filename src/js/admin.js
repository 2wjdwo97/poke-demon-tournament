// ── Hitmap renderer (shared) ───────────────────────────────────

function renderHitmap(container, hit, onChange) {
  let mask = hitToMask(hit);
  const wrap = document.createElement('div');
  wrap.className = 'hitmap-wrap';
  const label = document.createElement('div');
  label.className = 'hm-label';
  label.textContent = '← bk | atk | fw→';
  wrap.appendChild(label);
  const grid = document.createElement('div');
  grid.className = 'hitmap-grid';
  for (let dr = -1; dr <= 1; dr++) {
    for (let dc = -1; dc <= 1; dc++) {
      const cell = document.createElement('div');
      const isOrigin = dc === 0 && dr === 0;
      const bit = (dc + 1) + (dr + 1) * 3;
      const active = !!(mask & (1 << bit));
      cell.className = 'hm-cell' + (isOrigin ? ' hm-origin' : '') + (active ? ' hm-active' : '');
      cell.title = isOrigin ? 'Attacker [0,0]' : `dc=${dc} dr=${dr}`;
      cell.addEventListener('click', () => {
        mask ^= (1 << bit);
        onChange(mask);
        container.innerHTML = '';
        renderHitmap(container, mask, onChange);
      });
      grid.appendChild(cell);
    }
  }
  wrap.appendChild(grid);
  container.appendChild(wrap);
}

