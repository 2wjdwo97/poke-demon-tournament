function getMoveConfig(pad) {
  const saved = config.pokemon?.[pad];
  if (saved) return { fixedMoves: saved.fixedMoves || [], randomPool: saved.randomPool || [], randomCount: saved.randomCount ?? 3 };
  // POKEMON_LEARNSETS (hand-crafted defaults)
  if (typeof POKEMON_LEARNSETS !== 'undefined' && POKEMON_LEARNSETS[pad]) {
    const ls = POKEMON_LEARNSETS[pad];
    return { fixedMoves: [...ls.fixedMoves], randomPool: [...ls.randomPool], randomCount: ls.randomCount ?? 3 };
  }
  // STARTERS fallback
  if (typeof STARTERS !== 'undefined' && STARTERS[pad]) {
    const pool = STARTERS[pad].movepool || [];
    return { fixedMoves: pool.slice(0, 1), randomPool: pool.slice(1), randomCount: Math.min(3, pool.length - 1) };
  }
  // Type-based fallback
  const entry = (typeof POKEDEX !== 'undefined') ? POKEDEX[pad] : null;
  const types = entry?.types || ['Normal'];
  const pool  = [];
  if (typeof TYPE_MOVEPOOLS !== 'undefined') {
    for (const t of types) for (const m of (TYPE_MOVEPOOLS[t] || [])) if (!pool.includes(m)) pool.push(m);
  }
  if (!pool.includes('tackle')) pool.unshift('tackle');
  return { fixedMoves: [pool[0] || 'tackle'], randomPool: pool.slice(1, Math.min(pool.length, 7)), randomCount: 3 };
}

function getLevelMovesConfig(pad) {
  if (config.pokemon?.[pad]?.levelMoves) return [...config.pokemon[pad].levelMoves];
  if (typeof POKEMON_LEARNSETS !== 'undefined' && POKEMON_LEARNSETS[pad]?.levelMoves)
    return [...POKEMON_LEARNSETS[pad].levelMoves];
  return [];
}

function saveMoveConfig(pad, cfg) {
  if (!config.pokemon) config.pokemon = {};
  const existing = config.pokemon[pad] || {};
  config.pokemon[pad] = { ...existing, fixedMoves: cfg.fixedMoves, randomPool: cfg.randomPool, randomCount: cfg.randomCount };
}

function saveLevelMoves(pad, levelMoves) {
  if (!config.pokemon) config.pokemon = {};
  const existing = config.pokemon[pad] || {};
  config.pokemon[pad] = { ...existing, levelMoves };
}

function renderMoveConfig(pad) {
  const container = document.getElementById('pk-move-config');
  if (!container) return;
  const cfg = getMoveConfig(pad);

  function rebuild() {
    container.innerHTML = '';

    const allMoveKeys = Object.keys((config.moves && Object.keys(config.moves).length) ? config.moves : (typeof MOVES !== 'undefined' ? MOVES : {}));

    function buildTagList(arr, onRemove) {
      const wrap = document.createElement('div');
      wrap.className = 'move-tags';
      if (!arr.length) { const e = document.createElement('span'); e.className = 'move-empty'; e.textContent = 'none'; wrap.appendChild(e); return wrap; }
      arr.forEach((key, i) => {
        const tag = document.createElement('div');
        tag.className = 'move-tag';
        tag.innerHTML = `<span>${key}</span><button title="Remove">×</button>`;
        tag.querySelector('button').addEventListener('click', () => { arr.splice(i, 1); saveMoveConfig(pad, cfg); rebuild(); });
        wrap.appendChild(tag);
      });
      return wrap;
    }

    function buildAddRow(arr, label) {
      const row = document.createElement('div');
      row.className = 'mc-add-row';
      const sel = document.createElement('select');
      sel.className = 'sel-input';
      const emptyOpt = document.createElement('option');
      emptyOpt.value = ''; emptyOpt.textContent = '— pick move —';
      sel.appendChild(emptyOpt);
      allMoveKeys.filter(k => !arr.includes(k)).forEach(k => {
        const opt = document.createElement('option');
        opt.value = k; opt.textContent = k;
        sel.appendChild(opt);
      });
      const btn = document.createElement('button');
      btn.className = 'btn-gold-sm'; btn.textContent = '+ Add';
      btn.addEventListener('click', () => {
        if (!sel.value) return;
        arr.push(sel.value); saveMoveConfig(pad, cfg); rebuild();
      });
      row.appendChild(sel); row.appendChild(btn);
      return row;
    }

    // Fixed moves section
    const fixedSection = document.createElement('div');
    fixedSection.className = 'mc-row';
    const fixedLabel = document.createElement('div');
    fixedLabel.className = 'mc-label';
    fixedLabel.textContent = 'Fixed Moves (always in moveset):';
    fixedSection.appendChild(fixedLabel);
    fixedSection.appendChild(buildTagList(cfg.fixedMoves, i => { cfg.fixedMoves.splice(i,1); saveMoveConfig(pad,cfg); rebuild(); }));
    fixedSection.appendChild(buildAddRow(cfg.fixedMoves, 'fixed'));
    container.appendChild(fixedSection);

    // Random pool section
    const randomSection = document.createElement('div');
    randomSection.className = 'mc-row';
    const randomLabel = document.createElement('div');
    randomLabel.className = 'mc-label';
    randomLabel.innerHTML = `Random Pool (pick <input type="number" class="num-input" style="width:40px" value="${cfg.randomCount}" min="0" max="8"> from):`;
    randomLabel.querySelector('input').addEventListener('change', e => {
      cfg.randomCount = Math.max(0, Math.min(8, parseInt(e.target.value) || 0));
      saveMoveConfig(pad, cfg); rebuild();
    });
    randomSection.appendChild(randomLabel);
    randomSection.appendChild(buildTagList(cfg.randomPool, i => { cfg.randomPool.splice(i,1); saveMoveConfig(pad,cfg); rebuild(); }));
    randomSection.appendChild(buildAddRow(cfg.randomPool, 'random'));
    container.appendChild(randomSection);

    // Summary
    const total = cfg.fixedMoves.length + cfg.randomCount;
    const summary = document.createElement('div');
    summary.className = 'mc-summary' + (total > 8 ? ' warn' : '');
    summary.textContent = `Total: ${cfg.fixedMoves.length} fixed + ${cfg.randomCount} random = ${total} move${total !== 1 ? 's' : ''} per battle${total > 8 ? ' ⚠ exceeds 8 (will be capped)' : ''}`;
    container.appendChild(summary);
  }

  rebuild();
}

