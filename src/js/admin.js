function renderFloorPokeMoveCfg(container, floorNum, idx) {
  const entry = config.floors[floorNum].pokemon[idx];
  if (!entry.fixedMoves)  entry.fixedMoves  = [];
  if (!entry.randomPool)  entry.randomPool  = [];
  if (entry.randomCount == null) entry.randomCount = 3;

  const allMoveKeys = Object.keys((config.moves && Object.keys(config.moves).length) ? config.moves : (typeof MOVES !== 'undefined' ? MOVES : {}));
  const getMvName = k => (config.moves?.[k]?.name || (typeof MOVES !== 'undefined' && MOVES[k]?.name) || k);

  function saveAndMark() {
    const hasMoves = !!(entry.fixedMoves.length || entry.randomPool.length);
    // find the btn-cfg in the sibling row (the detail row's previous sibling)
    const cfgBtn = container.closest('tr')?.previousElementSibling?.querySelector('.btn-cfg');
    if (cfgBtn) cfgBtn.classList.toggle('has-cfg', hasMoves);
  }

  function buildTagList(arr, onRemove) {
    const wrap = document.createElement('div');
    wrap.className = 'move-tags';
    if (!arr.length) {
      const e = document.createElement('span'); e.className = 'move-empty'; e.textContent = 'none';
      wrap.appendChild(e); return wrap;
    }
    arr.forEach((key, i) => {
      const tag = document.createElement('div');
      tag.className = 'move-tag';
      tag.innerHTML = `<span>${getMvName(key)}</span><button title="Remove">×</button>`;
      tag.querySelector('button').addEventListener('click', () => { onRemove(i); });
      wrap.appendChild(tag);
    });
    return wrap;
  }

  function buildAddRow(arr, onAdd) {
    const row = document.createElement('div');
    row.className = 'mc-add-row';
    const sel = document.createElement('select');
    sel.className = 'sel-input';
    sel.innerHTML = '<option value="">— pick move —</option>';
    allMoveKeys.filter(k => !arr.includes(k)).forEach(k => {
      const opt = document.createElement('option');
      opt.value = k; opt.textContent = getMvName(k);
      sel.appendChild(opt);
    });
    const btn = document.createElement('button');
    btn.className = 'btn-gold-sm'; btn.textContent = '+ Add';
    btn.addEventListener('click', () => { if (sel.value) onAdd(sel.value); });
    row.appendChild(sel); row.appendChild(btn);
    return row;
  }

  function rebuild() {
    container.innerHTML = '';

    const hint = document.createElement('div');
    hint.className = 'poke-cfg-hint';
    hint.textContent = 'Empty = use floor-wide pool or type-based';
    container.appendChild(hint);

    // Fixed moves
    const fixedSection = document.createElement('div');
    fixedSection.className = 'mc-row';
    const fixedLabel = document.createElement('div');
    fixedLabel.className = 'mc-label';
    fixedLabel.textContent = 'Fixed Moves (always in moveset):';
    fixedSection.appendChild(fixedLabel);
    fixedSection.appendChild(buildTagList(entry.fixedMoves, i => { entry.fixedMoves.splice(i, 1); saveAndMark(); rebuild(); }));
    fixedSection.appendChild(buildAddRow(entry.fixedMoves, k => { entry.fixedMoves.push(k); saveAndMark(); rebuild(); }));
    container.appendChild(fixedSection);

    // Random pool
    const randomSection = document.createElement('div');
    randomSection.className = 'mc-row';
    const randomLabel = document.createElement('div');
    randomLabel.className = 'mc-label';
    randomLabel.innerHTML = `Random Pool (pick <input type="number" class="num-input" style="width:40px" value="${entry.randomCount}" min="0" max="8"> from):`;
    randomLabel.querySelector('input').addEventListener('change', e => {
      entry.randomCount = Math.max(0, Math.min(8, parseInt(e.target.value) || 0));
    });
    randomSection.appendChild(randomLabel);
    randomSection.appendChild(buildTagList(entry.randomPool, i => { entry.randomPool.splice(i, 1); saveAndMark(); rebuild(); }));
    randomSection.appendChild(buildAddRow(entry.randomPool, k => { entry.randomPool.push(k); saveAndMark(); rebuild(); }));
    container.appendChild(randomSection);

    const total = entry.fixedMoves.length + entry.randomCount;
    const summary = document.createElement('div');
    summary.className = 'mc-summary' + (total > 8 ? ' warn' : '');
    summary.textContent = `Total: ${entry.fixedMoves.length} fixed + ${entry.randomCount} random = ${total}${total > 8 ? ' ⚠ exceeds 8' : ''}`;
    container.appendChild(summary);
  }

  rebuild();
}

// ── Sprite drawing ─────────────────────────────────────────────

async function drawAdminSprite(canvas, pad, size) {
  if (!canvas || typeof loadAnimDataFromXml !== 'function') return;
  try {
    const basePath = `assets/chars/${pad}/`;
    const animData = await loadAnimDataFromXml(basePath);
    if (!animData) return;
    const animName = animData['Walk'] ? 'Walk' : (animData['Idle'] ? 'Idle' : null);
    if (!animName) return;
    const { fw, fh } = animData[animName];
    const img = await new Promise((res, rej) => {
      const el = new Image(); el.onload = () => res(el); el.onerror = () => rej();
      el.src = `${basePath}${animName}-Anim.png`;
    });
    const ctx = canvas.getContext('2d');
    ctx.imageSmoothingEnabled = false;
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    const srcX = 0, srcY = 1 * fh; // DIR_SW = 1
    const scale = Math.min(canvas.width / fw, canvas.height / fh);
    const dw = Math.floor(fw * scale), dh = Math.floor(fh * scale);
    const dx = Math.floor((canvas.width - dw) / 2), dy = Math.floor((canvas.height - dh) / 2);
    ctx.drawImage(img, srcX, srcY, fw, fh, dx, dy, dw, dh);
  } catch(e) {}
}

