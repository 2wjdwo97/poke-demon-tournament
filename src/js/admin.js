function getDefaultConfig() {
  const floors = {};
  for (let f = 1; f <= 4; f++) {
    const tbl = (typeof WILD_TABLES !== 'undefined' && WILD_TABLES[`floor${f}`]) || [];
    const bd  = (typeof BOSSES !== 'undefined' && BOSSES[`floor${f}`]) || null;
    floors[f] = {
      ...DEFAULT_FLOOR_RANGES[f],
      pokemon: tbl.map(([pad, weight]) => ({ pad, weight: parseInt(weight) || 6, catchRate: null })),
      movepool: [],
      boss: bd ? { pad: bd.pad, level: bd.level, fixedMoves: [...(bd.movepool || [])], randomPool: [], randomCount: 0 } : null,
    };
  }
  const moves = {};
  if (typeof MOVES !== 'undefined') {
    for (const [key, mv] of Object.entries(MOVES)) {
      moves[key] = { ...mv };
    }
  }
  return { version: 1, floors, moves, evolution: {}, pokemon: {} };
}

function loadConfig() {
  const saved = (typeof GAME_CONFIG !== 'undefined' && GAME_CONFIG) ? GAME_CONFIG : null;
  if (saved) {
    config = JSON.parse(JSON.stringify(saved));
    for (let f = 1; f <= 4; f++) {
      if (!config.floors || !config.floors[f]) {
        if (!config.floors) config.floors = {};
        const tbl = (typeof WILD_TABLES !== 'undefined' && WILD_TABLES[`floor${f}`]) || [];
        config.floors[f] = { ...DEFAULT_FLOOR_RANGES[f], pokemon: tbl.map(([pad, weight]) => ({ pad, weight: parseInt(weight) || 6, catchRate: null })), movepool: [] };
      }
    }
    if (typeof MOVES !== 'undefined') {
      if (!config.moves) config.moves = {};
      for (const [key, mv] of Object.entries(MOVES)) {
        if (!config.moves[key]) {
          config.moves[key] = { ...mv };
        } else {
          const repairZero = ['guardAmt', 'healAmt', 'enHealPct'];
          for (const [field, val] of Object.entries(mv)) {
            if (field === 'hit') continue;
            if (!(field in config.moves[key])) {
              config.moves[key][field] = val;
            } else if (repairZero.includes(field) && !config.moves[key][field] && val) {
              config.moves[key][field] = val;
            }
          }
        }
      }
    }
    for (const mv of Object.values(config.moves)) {
      if (Array.isArray(mv.hit)) mv.hit = hitToMask(mv.hit);
    }
    if (!config.evolution) config.evolution = {};
    if (!config.pokemon)   config.pokemon   = {};
    for (let f = 1; f <= 4; f++) {
      if (config.floors[f] && !config.floors[f].movepool) config.floors[f].movepool = [];
      if (config.floors[f] && !('boss' in config.floors[f])) {
        const bd = (typeof BOSSES !== 'undefined' && BOSSES[`floor${f}`]) || null;
        config.floors[f].boss = bd ? { pad: bd.pad, level: bd.level, fixedMoves: [...(bd.movepool || [])], randomPool: [], randomCount: 0 } : null;
      }
    }
  } else {
    config = getDefaultConfig();
  }
}

async function saveConfig() {
  const content = generateConfigJs();

  let handle = await _idbGetHandle();
  if (handle) {
    try {
      const perm = await handle.queryPermission({ mode: 'readwrite' });
      if (perm !== 'granted') {
        const req = await handle.requestPermission({ mode: 'readwrite' });
        if (req !== 'granted') handle = null;
      }
    } catch { handle = null; }
  }

  if (!handle) {
    if (!window.showSaveFilePicker) {
      // Fallback for non-Chromium: download the file
      const blob = new Blob([content], { type: 'application/javascript' });
      const url  = URL.createObjectURL(blob);
      const a    = document.createElement('a');
      a.href = url; a.download = 'gameconfig.js'; a.click();
      URL.revokeObjectURL(url);
      showToast('Downloaded gameconfig.js — place in js/data/ folder');
      return;
    }
    try {
      handle = await window.showSaveFilePicker({
        suggestedName: 'gameconfig.js',
        types: [{ description: 'JS Config', accept: { 'application/javascript': ['.js'] } }],
      });
      await _idbSetHandle(handle);
    } catch(e) {
      if (e.name !== 'AbortError') showToast('Save cancelled');
      return;
    }
  }

  try {
    const writable = await handle.createWritable();
    await writable.write(content);
    await writable.close();
    showToast(`Saved → ${handle.name} ✓  (reload game to apply)`);
    updateSaveStatus(handle.name);
  } catch(e) {
    await _idbClearHandle();
    showToast('Write failed — try again: ' + e.message);
  }
}

