function isBaseFormPad(pad) {
  if (typeof EVOLUTION_CHAINS === 'undefined') return true;
  return !Object.values(EVOLUTION_CHAINS).some(v => v.to === pad);
}

function getEvoChain(basePad) {
  const chain = [basePad];
  const evo   = config.evolution || {};
  let current = basePad;
  for (;;) {
    const next = evo[current] || (typeof EVOLUTION_CHAINS !== 'undefined' && EVOLUTION_CHAINS[current]);
    if (!next) break;
    chain.push(next.to);
    current = next.to;
  }
  return chain;
}

function getEvoLink(fromPad) {
  const evo = config.evolution || {};
  return evo[fromPad] || (typeof EVOLUTION_CHAINS !== 'undefined' && EVOLUTION_CHAINS[fromPad]) || null;
}

